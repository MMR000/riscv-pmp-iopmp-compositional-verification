def git_head() -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, text=True
        ).strip()
    except Exception:
        return "unknown"


def read_csv(path: Path) -> list[dict]:
    with path.open(newline="") as f:
        return list(csv.DictReader(f))


def esc(s: str) -> str:
    return (
        s.replace("\\", "\\textbackslash{}")
        .replace("_", "\\_")
        .replace("&", "\\&")
        .replace("%", "\\%")
    )


def safe_macro_id(pid: str) -> str:
    digit_words = "Zero One Two Three Four Five Six Seven Eight Nine".split()
    out: list[str] = []
    for c in pid:
        if c.isdigit():
            out.append(digit_words[int(c)])
        elif c in "-_":
            continue
        else:
            out.append(c)
    return "".join(out)


def macro_name(pid: str, field: str) -> str:
    return f"\\Evidence{safe_macro_id(pid)}{field}"


def status_label(row: dict, col: str) -> str:
    v = row.get(col, "NOT_RUN")
    c = row.get("classification", v)
    if col == "pdr_result" and v == "FAIL":
        return f"{v} (raw; see classification: {c})"
    return v


def write_macros(rows: list[dict]) -> None:
    lines = [
        "% Auto-generated by scripts/analysis/generate_paper_artifacts.py",
        f"% Do not edit manually",
        "",
        f"\\newcommand{{\\GitCommitMFiveTen}}{{681b2bd}}",
        f"\\newcommand{{\\GitCommitCurrent}}{{{git_head()}}}",
        f"\\newcommand{{\\EvidenceFreezeDate}}{{{datetime.now(timezone.utc).strftime('%Y-%m-%d')}}}",
        "",
    ]
    for r in rows:
        pid = r["property_id"]
        lines.append(f"\\newcommand{{{macro_name(pid, 'Sim')}}}{{{esc(r.get('simulation_result',''))}}}")
        lines.append(f"\\newcommand{{{macro_name(pid, 'Bmc')}}}{{{esc(r.get('bmc_result',''))}}}")
        lines.append(f"\\newcommand{{{macro_name(pid, 'Pdr')}}}{{{esc(status_label(r, 'pdr_result'))}}}")
        lines.append(f"\\newcommand{{{macro_name(pid, 'Class')}}}{{{esc(r.get('classification',''))}}}")
        lines.append("")
    OUT_MACROS.parent.mkdir(parents=True, exist_ok=True)
    OUT_MACROS.write_text("\n".join(lines) + "\n")


def write_provenance() -> None:
    script_hash = hashlib.sha256(Path(__file__).read_bytes()).hexdigest()[:12]
    text = f"""% Auto-generated provenance
\\newcommand{{\\ProvenanceCommit}}{{{git_head()}}}
\\newcommand{{\\ProvenanceScriptHash}}{{{script_hash}}}
\\newcommand{{\\ProvenanceGenerated}}{{{datetime.now(timezone.utc).isoformat()}}}
\\newcommand{{\\ProvenanceGuaranteeCsv}}{{results/tables/m510\\_guarantee\\_matrix.csv}}
\\newcommand{{\\ProvenanceSensitivityCsv}}{{results/tables/m510\\_assumption\\_sensitivity.csv}}
"""
    OUT_PROV.write_text(text)


MAIN_PAPER_PROPS = [
    "SP-02", "SP-04", "SP-06", "SP-08-RST-A", "SP-08-RST-B", "M57-FP-04-FIX2"
]


def write_property_summary(rows: list[dict]) -> None:
    by_id = {r["property_id"]: r for r in rows}
    lines = [
        "% Auto-generated property summary (main paper subset)",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Representative security properties: simulation vs formal methods. "
        "PDR column shows raw engine status where applicable; scientific classification is separate.}",
        "\\label{tab:property-summary}",
        "\\small",
        "\\begin{tabularx}{\\linewidth}{@{}lXXXXl@{}}",
        "\\toprule",
        "Property & Sim & BMC & PDR/Induct. & Scientific status \\\\",
        "\\midrule",
    ]
    for pid in MAIN_PAPER_PROPS:
        r = by_id.get(pid)
        if not r:
            continue
        pdr = status_label(r, "pdr_result")
        lines.append(
            f"{esc(pid)} & {esc(r['simulation_result'])} & {esc(r['bmc_result'])} & "
            f"{esc(pdr)} & {esc(r['classification'])} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabularx}", "\\end{table}"]
    OUT_PROP.write_text("\n".join(lines) + "\n")


def write_reset_comparison(rows: list[dict]) -> None:
    by_id = {r["property_id"]: r for r in rows}
    ra, rb = by_id.get("SP-08-RST-A", {}), by_id.get("SP-08-RST-B", {})
    lines = [
        "% Auto-generated reset model comparison",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{RST-A (fail-open) vs RST-B (fail-closed) under SP-08. "
        "RST-A counterexample is classified as reset-assumption dependency, not a vulnerability.}",
        "\\label{tab:reset-comparison}",
        "\\begin{tabular}{@{}lllll@{}}",
        "\\toprule",
        "Model & Default & DMA before \\texttt{secure\\_ready} & Formal & Classification \\\\",
        "\\midrule",
        f"RST-A & fail-open & reachable (CE) & {esc(ra.get('bmc_result',''))} & "
        f"{esc(ra.get('classification',''))} \\\\",
        f"RST-B & fail-closed & unreachable & k-induction proof & "
        f"{esc(rb.get('classification',''))} \\\\",
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    OUT_RST.write_text("\n".join(lines) + "\n")


def write_assumption_sensitivity(rows: list[dict]) -> None:
    subset = rows[:6]
    lines = [
        "% Auto-generated assumption sensitivity (main paper subset)",
        "\\begin{table}[t]",
        "\\centering",
        "\\caption{Assumption sensitivity (subset). Full matrix in appendix.}",
        "\\label{tab:assumption-sensitivity}",
        "\\small",
        "\\begin{tabularx}{\\linewidth}{@{}lXXl@{}}",
        "\\toprule",
        "Assumption & Baseline & If removed/weakened & Classification \\\\",
        "\\midrule",
    ]
    for r in subset:
        lines.append(
            f"{esc(r.get('assumption_id',''))} & {esc(r.get('baseline_status',''))} & "
            f"{esc(r.get('weakened_status',''))} & {esc(r.get('classification',''))} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabularx}", "\\end{table}"]
    OUT_SENS.write_text("\n".join(lines) + "\n")


def write_formal_results(rows: list[dict]) -> None:
    lines = [
        "% Auto-generated formal results table",
        "\\input{tables/property_summary.tex}",
        "\\input{tables/reset_comparison.tex}",
    ]
    OUT_FORMAL.write_text("\n".join(lines) + "\n")


def write_claims_tex(claims: list[dict]) -> None:
    lines = [
        "% Auto-generated claims-to-evidence (main paper subset)",
        "\\begin{table*}[t]",
        "\\centering",
        "\\caption{Claims-to-evidence mapping (subset). Full register: \\texttt{results/m6/claims\\_evidence.csv}.}",
        "\\label{tab:claims-evidence}",
        "\\footnotesize",
        "\\begin{tabularx}{\\textwidth}{@{}lXll@{}}",
        "\\toprule",
        "ID & Claim & Status & Evidence \\\\",
        "\\midrule",
    ]
    for c in claims[:8]:
        lines.append(
            f"{esc(c['claim_id'])} & {esc(c['claim_text'][:80])}... & "
            f"{esc(c['scientific_status'])} & {esc(c['evidence_file'][:40])} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabularx}", "\\end{table*}"]
    OUT_CLAIMS.write_text("\n".join(lines) + "\n")


