def write_claims_csv_md() -> None:
    fields = list(CLAIMS[0].keys())
    csv_path = ROOT / "results" / "m6" / "claims_evidence.csv"
    md_path = ROOT / "results" / "m6" / "claims_evidence.md"
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    with csv_path.open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(CLAIMS)
    md_lines = ["# Claims-to-evidence register (M6)\n"]
    for c in CLAIMS:
        md_lines.append(f"## {c['claim_id']}\n")
        for k, v in c.items():
            md_lines.append(f"- **{k}**: {v}")
        md_lines.append("")
    md_path.write_text("\n".join(md_lines))


def ensure_dirs() -> None:
    for d in (OUT_MACROS.parent, OUT_PROP.parent, OUT_RST.parent, OUT_SENS.parent,
              OUT_FORMAL.parent, OUT_CLAIMS.parent):
        d.mkdir(parents=True, exist_ok=True)


def main() -> int:
    ensure_dirs()
    rows = read_csv(GUAR)
    sens = read_csv(SENS)
    write_macros(rows)
    write_provenance()
    write_property_summary(rows)
    write_reset_comparison(rows)
    write_assumption_sensitivity(sens)
    write_formal_results(rows)
    write_claims_csv_md()
    write_claims_tex(CLAIMS)
    print(f"Generated paper artifacts under {ROOT / 'paper'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
